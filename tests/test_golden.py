class TestGolden(unittest.TestCase):
    def test_constants(self):
        self.assertEqual((hp.PI, hp.LN2, hp.LN10), (PI, LN2, LN10))

    def test_sincos(self):
        for a, s, c in SINCOS:
            self.assertEqual(hp.sincos(D(a)), (s, c), a)

    def test_ln(self):
        for x, v in LN:
            self.assertEqual(hp.ln(D(x)), v, x)
        self.assertEqual(hp.ln(hp.P), 0)

    def test_ln_normalization_assumption(self):
        self.assertEqual(hp.P.bit_length(), 299)
        self.assertTrue(2 ** 298 * 2 > hp.P > 2 ** 298)


